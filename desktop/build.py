"""Build a matched desktop release from a selected Git revision on its native runner."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import stat
import subprocess
import tarfile
from tempfile import TemporaryDirectory
import zipfile


ROOT = Path(__file__).resolve().parents[1]
TARGETS = {"macos-arm64": "bin/python3.11", "macos-x86_64": "bin/python3.11",
           "windows-x86_64": "python.exe"}


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def member(archive, name, mode):
    info = zipfile.ZipInfo(name)
    info.create_system = 3
    info.external_attr = (stat.S_IFREG | mode) << 16
    info.compress_type = zipfile.ZIP_DEFLATED
    return archive.open(info, "w")


def pack(out, runtime, revision, target, version):
    if not re.fullmatch("[0-9a-f]{40}", revision) or target not in TARGETS:
        raise ValueError("A full commit SHA and supported OS/CPU target are required")
    if not (runtime / TARGETS[target]).is_file():
        raise ValueError("Private runtime is missing its target interpreter")
    out.mkdir(parents=True, exist_ok=True)
    name = f"sau-desktop-{revision}-{target}.zip"
    with TemporaryDirectory(dir=out) as temporary:
        artifact = Path(temporary) / name
        with zipfile.ZipFile(artifact, "w") as archive:
            manifest = dict(schema=1, revision=revision, target=target, version=version)
            with member(archive, "release.json", 0o644) as destination:
                destination.write(json.dumps(manifest, sort_keys=True).encode())
            for path in sorted(runtime.rglob("*")):
                if path.is_dir() or "__pycache__" in path.parts or path.suffix == ".pyc":
                    continue
                resolved = path.resolve(strict=True)
                if not resolved.is_relative_to(runtime.resolve()) or not resolved.is_file():
                    raise ValueError(f"Non-portable runtime entry: {path.relative_to(runtime)}")
                name_in_zip = "runtime/" + path.relative_to(runtime).as_posix()
                mode = 0o755 if path.stat().st_mode & 0o111 else 0o644
                with path.open("rb") as source, member(archive, name_in_zip, mode) as destination:
                    shutil.copyfileobj(source, destination)
        checksum = artifact.with_suffix(".sha256")
        checksum.write_text(f"{digest(artifact)}  {name}\n", encoding="ascii")
        artifact.replace(out / name)
        checksum.replace((out / name).with_suffix(".sha256"))
    return out / name


def runtime_digest(root):
    # Bind names, link destinations, executable bits and bytes. Skip generated bytecode.
    tree = hashlib.sha256()
    for path in sorted(root.rglob("*")):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            if (path.readlink().is_absolute() or not path.resolve(strict=True).is_relative_to(root.resolve())
                    or path.is_dir()):
                raise ValueError("Runtime contains an external or directory link")
            contents = ["link", str(path.readlink())]
        elif path.is_file():
            contents = ["file", bool(path.stat().st_mode & 0o111), digest(path)]
        elif path.is_dir():
            continue
        else:
            raise ValueError("Runtime contains a special file")
        tree.update(json.dumps([path.relative_to(root).as_posix(), *contents]).encode() + b"\n")
    return tree.hexdigest()


def build(args):
    if not args.runtime.is_dir() or runtime_digest(args.runtime) != args.runtime_sha256:
        raise ValueError("Runtime SHA-256 mismatch")
    if not re.fullmatch("[0-9a-f]{40}", args.revision):
        raise ValueError("An explicit full commit SHA is required")
    with TemporaryDirectory() as scratch:
        tmp = Path(scratch).resolve()
        runtime = tmp / "runtime"
        shutil.copytree(args.runtime, runtime, symlinks=True,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        if runtime_digest(runtime) != args.runtime_sha256:
            raise ValueError("Runtime changed while copying")
        python = runtime / TARGETS[args.target]
        probe = ("import json, platform, sys, sysconfig;"
                 "print(json.dumps([platform.system(),platform.machine(),sys.version_info[:3],"
                 "sys.prefix,sysconfig.get_path('purelib')]))")
        system, cpu, version, prefix, site = json.loads(subprocess.check_output([python, "-IB", "-c", probe]))
        native = {("Darwin", "arm64"): "macos-arm64", ("Darwin", "x86_64"): "macos-x86_64",
                  ("Windows", "amd64"): "windows-x86_64"}.get((system, cpu.lower()))
        if (native != args.target or version != [3, 11, 11] or Path(prefix).resolve() != runtime
                or not Path(site).resolve().is_relative_to(runtime) or (runtime / "pyvenv.cfg").exists()):
            raise ValueError("Use matching, relocatable standalone CPython 3.11.11 on its native runner")
        source = tmp / "source"
        source.mkdir()
        archive = tmp / "source.tar"
        subprocess.run(["git", "-C", ROOT, "archive", "-o", archive, args.revision, "--", "cli", "cli-service",
                        "LICENSE", "pyproject.toml", "README.md", "desktop/requirements.lock"], check=True)
        with tarfile.open(archive) as tar:
            tar.extractall(source, filter="data")
        wheels = tmp / "wheels"
        env = {**os.environ, "SOURCE_DATE_EPOCH": "946684800", "PYTHONDONTWRITEBYTECODE": "1"}
        constraint = tmp / "build-constraint.txt"
        constraint.write_text("setuptools==80.9.0\n", encoding="ascii")
        for project in (source, source / "cli-service"):
            subprocess.run(["uv", "build", "--no-config", "--python", python, "--wheel", "--build-constraint",
                            constraint, "--out-dir", wheels, project], check=True, env=env)
        packages = tmp / "packages"
        install = ["uv", "pip", "install", "--no-config", "--python", python,
                   "--target", packages, "--only-binary", ":all:", "--link-mode", "copy"]
        subprocess.run([*install, "--require-hashes", "-r", source / "desktop/requirements.lock"], check=True)
        subprocess.run([*install, "--no-deps", "--no-index", "--find-links", wheels, "social-auto-upload",
                        "social-media-worker"], check=True)
        for entry in packages.iterdir():
            if entry.name in ("bin", "Scripts", ".lock"):
                continue  # Generated shell entry points contain paths to this build stage.
            if entry.is_dir():
                shutil.copytree(entry, Path(site) / entry.name, dirs_exist_ok=True,
                                ignore=shutil.ignore_patterns("uv_cache.json"))
            else:
                shutil.copyfile(entry, Path(site) / entry.name)
        smoke = ("import cv2, patchright, httpx, sau_worker, sau_cli;"
                 "from importlib.metadata import version;"
                 "assert version('social-auto-upload') == sau_worker.__version__ == version('social-media-worker');"
                 "print(sau_worker.__version__)")
        version = subprocess.check_output([python, "-IB", "-c", smoke], env={**env, "SAU_HOME": str(tmp / "data")},
                                          cwd=tmp, text=True).strip()
        return pack(args.out.resolve(), runtime, args.revision, args.target, version)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("runtime-digest").add_argument("runtime", type=Path)
    package = commands.add_parser("build")
    package.add_argument("--runtime", type=Path, required=True)
    package.add_argument("--runtime-sha256", required=True)
    package.add_argument("--revision", required=True)
    package.add_argument("--target", choices=TARGETS, required=True)
    package.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    try:
        print(runtime_digest(args.runtime) if args.command == "runtime-digest" else build(args))
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f"{exc}\n")
